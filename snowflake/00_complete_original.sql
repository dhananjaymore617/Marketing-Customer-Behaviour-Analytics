-- --------------------------------------------------------------------------------------------------------------------------------------------------------
-- CUSTOMER_JOURNEY EDA
DESC TABLE CUSTOMER_JOURNEY;
SELECT * FROM CUSTOMER_JOURNEY WHERE JOURNEYID IS NULL OR CUSTOMERID IS NULL OR PRODUCTID IS NULL;

-- IMPORTANT POINT 
-- OrderID, CustomerID,ProductID
-- Customer can bought twice
-- So as per this we can find duplicates with the OrderID becuase CustomerID and ProductID can be the same.

-- But OrderID and CustomerID can be the same but ProductID can be different because, same customer in one order can buy multiple products.
-- So sometimes finding duplicates using only OrderID can also make mistakes, thats why we group it by CustomerID, ProductID and OrderID.
-- ALL DUPLICATES
WITH DuplicateRecords AS
(SELECT JourneyID, CustomerID, ProductID, VisitDate, Stage, Action, Duration,
ROW_NUMBER() OVER(PARTITION BY CustomerID, ProductID, VisitDate, Stage, Action ORDER BY JourneyID) AS Row_Num
FROM customer_journey)
SELECT * FROM DuplicateRecords WHERE Row_Num > 1 ORDER BY JourneyID;

SELECT MIN(VISITDATE), MAX(VISITDATE) FROM CUSTOMER_JOURNEY;
SELECT ACTION, COUNT(ACTION) FROM CUSTOMER_JOURNEY GROUP BY ACTION ORDER BY COUNT(ACTION);
SELECT STAGE, COUNT(STAGE) FROM CUSTOMER_JOURNEY GROUP BY STAGE ORDER BY COUNT(STAGE);

SELECT MIN(DURATION), MAX(DURATION) FROM CUSTOMER_JOURNEY;

-- FINAL CLEAN JOURNEY TABLE
WITH CTE1 AS
(SELECT JOURNEYID, CUSTOMERID, PRODUCTID, VISITDATE, UPPER(STAGE) AS STAGE, ACTION, DURATION,
AVG(TRY_TO_NUMBER(DURATION)) OVER(PARTITION BY VISITDATE) AS AVG_DURATION,
ROW_NUMBER() OVER(PARTITION BY CUSTOMERID, PRODUCTID, VISITDATE, UPPER(STAGE), ACTION ORDER BY JOURNEYID) AS ROW_NUM
FROM CUSTOMER_JOURNEY)
SELECT JOURNEYID, CUSTOMERID, PRODUCTID, VISITDATE, STAGE, ACTION, COALESCE(TRY_TO_NUMBER(DURATION), AVG_DURATION) AS DURATION, ROW_NUM
FROM CTE1 WHERE ROW_NUM = 1;

-- CUSTOMER_REVIEWS EDA
DESC TABLE CUSTOMER_REVIEWS;
SELECT * FROM CUSTOMER_REVIEWS LIMIT 5;
SELECT * FROM CUSTOMER_REVIEWS WHERE REVIEW_ID IS NULL OR CUSTOMER_ID IS NULL OR PRODUCT_ID IS NULL OR REVIEW_DATE IS NULL OR RATING IS NULL OR REVIEW_TEXT IS NULL;
SELECT MIN(REVIEW_DATE), MAX(REVIEW_DATE) FROM CUSTOMER_REVIEWS;
SELECT MIN(RATING), MAX(RATING) FROM CUSTOMER_REVIEWS;

SELECT * FROM 
(SELECT *, ROW_NUMBER() OVER(PARTITION BY REVIEW_ID, CUSTOMER_ID, PRODUCT_ID, REVIEW_DATE, RATING, REVIEW_TEXT ORDER BY REVIEW_ID) AS ROW_NUM FROM CUSTOMER_REVIEWS)
WHERE ROW_NUM = 1;
-- --------------------------------------------------------------------------------------------------------------------------------------------------------
-- Customer_Engagement EDA
DESC TABLE CUSTOMERS_ENGAGEMENT;
SELECT * FROM CUSTOMERS_ENGAGEMENT LIMIT 5;
SELECT COUNT(*) FROM CUSTOMERS_ENGAGEMENT;

SELECT ENGAGEMENT_ID, COUNT(*) FROM CUSTOMERS_ENGAGEMENT GROUP BY ENGAGEMENT_ID HAVING COUNT(*) > 1;
SELECT * FROM CUSTOMERS_ENGAGEMENT WHERE ENGAGEMENT_ID IS NULL OR CONTENT_TYPE IS NULL OR LIKES IS NULL OR ENGAGEMENT_DATE IS NULL OR PRODUCT_ID IS NULL OR VIEWS_CLICKS IS NULL;
SELECT MIN(ENGAGEMENT_DATE), MAX(ENGAGEMENT_DATE) FROM CUSTOMERS_ENGAGEMENT;
SELECT CONTENT_TYPE, COUNT(CONTENT_TYPE) FROM CUSTOMERS_ENGAGEMENT GROUP BY CONTENT_TYPE ORDER BY COUNT(CONTENT_TYPE);

-- Clean and Normalize the Engagement Data Table

SELECT ENGAGEMENT_ID, CONTENT_ID, CAMPAIGN_ID, PRODUCT_ID,
       REPLACE(UPPER(CONTENT_TYPE),'SOCIALMEDIA', 'SOCIAL MEDIA') AS CONTENT_TYPE,
       TRY_TO_NUMBER(LEFT(VIEWS_CLICKS, CHARINDEX('-', VIEWS_CLICKS) -1 )) AS VIEWS,
       TRY_TO_NUMBER(RIGHT(VIEWS_CLICKS, LEN(VIEWS_CLICKS) - CHARINDEX('-', VIEWS_CLICKS))) AS CLICKS,
       LIKES, ENGAGEMENT_DATE
FROM CUSTOMERS_ENGAGEMENT
WHERE UPPER(TRIM(CONTENT_TYPE)) <> 'NEWSLETTER';
